using Glyph = std::vector<std::vector<Point2D>>;

Glyph g_line(std::initializer_list<std::initializer_list<Point2D>> strokes) {
    Glyph g;
    for (auto s : strokes) {
        g.emplace_back(s);
    }
    return g;
}

