std::vector<std::vector<Point2D>> mark_stick_text(
    const std::string& text,
    double origin_x,
    double origin_y,
    double height_mm,
    double spacing_mm) {
    std::vector<std::vector<Point2D>> out;
    const double w = height_mm * 0.7;
    double x = origin_x;
    for (char ch : text) {
        char up = static_cast<char>(std::toupper(static_cast<unsigned char>(ch)));
        auto it = font().find(up);
        if (it == font().end()) {
            it = font().find('-');
        }
        if (it != font().end()) {
            for (const auto& stroke : it->second) {
                std::vector<Point2D> s;
                for (const auto& p : stroke) {
                    s.push_back({x + p.x * w, origin_y + p.y * height_mm});
                }
                if (s.size() >= 2) {
                    out.push_back(std::move(s));
                }
            }
        }
        x += w + spacing_mm;
    }
    return out;
}

